import base64, io, sys
from PIL import Image
T='/home/claude/tex/'
def jpg(path,size=None,q=82,gray=False,crop=None):
    im=Image.open(T+path)
    if im.mode in ('P','RGBA','LA'): im=im.convert('RGB' if not gray else 'L')
    if gray: im=im.convert('L')
    else: im=im.convert('RGB')
    if size: im=im.resize(size,Image.LANCZOS)
    b=io.BytesIO(); im.save(b,'JPEG',quality=q,optimize=True,progressive=True)
    return b.getvalue()
def clouds():
    from PIL import ImageFilter
    import numpy as np
    im=Image.open(T+'earth_clouds_1024.png').convert('RGBA')
    a=im.getchannel('A').resize((2048,1024),Image.BICUBIC).filter(ImageFilter.GaussianBlur(0.8))
    n=np.array(a).astype(float)/255.0
    n=np.clip(n*1.35,0,1)**0.85
    out=Image.fromarray((n*255).astype('uint8'),'L')
    b=io.BytesIO(); out.save(b,'JPEG',quality=82,optimize=True,progressive=True)
    return b.getvalue()
